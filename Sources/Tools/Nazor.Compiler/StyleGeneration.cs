using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Nazor.Nss;
using Nazor.Style;

namespace Nazor.Compiler;

internal static class StyleGeneration
{
    public static (StyleSheet? Sheet, IReadOnlyList<NazorDiagnostic> Diagnostics) CompileComponentStyles(NazorCompilerOptions options, string sourcePath, IReadOnlyList<StyleSource> styles, Func<string, string?>? idType = null)
    {
        if (styles.Count == 0) return (null, []);
        var compilation = NssCompiler.Compile(SourceName(options, sourcePath), styles.Select(ToNssSource), idType);
        return (compilation.Success ? compilation.StyleSheet : null, compilation.Diagnostics.Select(ToNazor).ToArray());
    }

    public static string? ComponentRegistration(NazorCompilerOptions options, string componentCSharp, string sourcePath, IReadOnlyList<StyleSource> styles, List<NazorDiagnostic> diagnostics, Func<string, string?>? idType = null)
    {
        var (sheet, styleDiagnostics) = CompileComponentStyles(options, sourcePath, styles, idType);
        diagnostics.AddRange(styleDiagnostics);
        if (sheet is null) return null;
        var (ns, name, arity) = ComponentClass(componentCSharp);
        var scope = arity == 0 ? name : name + "<" + new string(',', arity - 1) + ">";
        var builder = new StringBuilder();
        builder.AppendLine();
        builder.AppendLine("#line default");
        if (ns is not null) builder.AppendLine($"namespace {ns}").AppendLine("{");
        builder.AppendLine("#pragma warning disable CA2255 // The module initializer registers the scoped stylesheet of a generated component.");
        builder.AppendLine(arity == 0 ? $"    partial class {name}" : $"    internal static class {StyleHotReload.GenericRegistrationClassPrefix}{name}");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine($"        internal static void {RegistrationMethod}() =>");
        builder.AppendLine($"            global::Nazor.Style.StyleRegistry.RegisterScoped(typeof({scope}), __NazorCreateStyleSheet);");
        builder.AppendLine(CSharpEmitter.EmitFactory(sheet, "__NazorCreateStyleSheet"));
        builder.AppendLine("    }");
        builder.AppendLine("#pragma warning restore CA2255");
        if (ns is not null) builder.AppendLine("}");
        return builder.ToString();
    }

    public const string RegistrationMethod = StyleHotReload.RegistrationMethod;

    public static NssCompilation CompileStyleSheet(NazorCompilerOptions options, string file, string text, Func<string, string?>? idType = null) =>
        NssCompiler.Compile(SourceName(options, file), [new NssSource(file, text)], idType);

    public static string StyleSheetsClass(NazorCompilerOptions options, IReadOnlyList<string> files, Func<string, string> readText, List<NazorDiagnostic> diagnostics, Func<string, string?>? idType = null)
    {
        var builder = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        builder.AppendLine($"namespace {options.RootNamespace}").AppendLine("{");
        builder.AppendLine("    /// <summary>Stylesheets compiled from the standalone .nss files of the project.</summary>");
        builder.AppendLine("    public static partial class StyleSheets").AppendLine("    {");
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in files.OrderBy(f => f, StringComparer.OrdinalIgnoreCase))
        {
            var compilation = CompileStyleSheet(options, file, readText(file), idType);
            diagnostics.AddRange(compilation.Diagnostics.Select(ToNazor));
            var name = Identifier(Path.GetFileNameWithoutExtension(file));
            if (!names.Add(name))
            {
                diagnostics.Add(new("NZS110", NazorDiagnosticSeverity.Error, file, 1, 1, $"Another stylesheet already produces the property 'StyleSheets.{name}'."));
                continue;
            }
            if (!compilation.Success) continue;
            builder.AppendLine($"        private static readonly global::System.Lazy<global::Nazor.Style.StyleSheet> __{name} = new(__NazorCreate_{name});");
            builder.AppendLine(CSharpEmitter.EmitFactory(compilation.StyleSheet, $"__NazorCreate_{name}"));
            builder.AppendLine($"        /// <summary>Gets the stylesheet compiled from <c>{System.Security.SecurityElement.Escape(Path.GetFileName(file))}</c>.</summary>");
            builder.AppendLine($"        public static global::Nazor.Style.StyleSheet {name} => __{name}.Value;");
        }
        builder.AppendLine("    }").AppendLine("}");
        return builder.ToString();
    }

    public static string SourceName(NazorCompilerOptions options, string path)
    {
        path = Path.GetFullPath(path);
        if (options.ProjectDirectory is { Length: > 0 } directory)
        {
            var relative = Path.GetRelativePath(Path.TrimEndingDirectorySeparator(Path.GetFullPath(directory)), path);
            if (!relative.StartsWith("..", StringComparison.Ordinal) && !Path.IsPathRooted(relative)) return relative.Replace('\\', '/');
        }
        return Path.GetFileName(path);
    }

    internal static (string? Namespace, string Name, int Arity) ComponentClass(string csharp)
    {
        var root = CSharpSyntaxTree.ParseText(csharp).GetRoot();
        var component = root.DescendantNodes().OfType<ClassDeclarationSyntax>()
            .First(c => c.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax);
        var ns = component.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(n => n.Name.ToString()).ToArray();
        return (ns.Length == 0 ? null : string.Join(".", ns), component.Identifier.Text, component.TypeParameterList?.Parameters.Count ?? 0);
    }

    internal static string ClrName(string? ns, string name, int arity)
    {
        var full = ns is null ? name : ns + "." + name;
        return arity == 0 ? full : full + "`" + arity.ToString(System.Globalization.CultureInfo.InvariantCulture);
    }

    private static NssSource ToNssSource(StyleSource style) => new(style.Path, style.Text, style.Line, style.Column);

    internal static NazorDiagnostic ToNazor(NssDiagnostic d) =>
        new(d.Id, d.IsError ? NazorDiagnosticSeverity.Error : NazorDiagnosticSeverity.Warning, d.Path, d.Line, d.Column, d.Message, d.Length);

    private static string Identifier(string name)
    {
        var builder = new StringBuilder();
        var upper = true;
        foreach (var c in name)
        {
            if (!char.IsLetterOrDigit(c))
            {
                upper = true;
                continue;
            }
            builder.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }
        if (builder.Length == 0 || char.IsDigit(builder[0])) builder.Insert(0, '_');
        return builder.ToString();
    }
}
