using System.Text;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Nazor.Compiler;

// Generate static wire bindings from the existing private desktop contracts; no runtime reflection or proxy emission.
internal sealed class DBusBindings
{
    private readonly StringBuilder code = new();
    private readonly Dictionary<string, (ITypeSymbol Type, int Id)> codecs = new(StringComparer.Ordinal);
    private static string Type(ITypeSymbol type) => type switch
    {
        IArrayTypeSymbol array => Type(array.ElementType) + "[]",
        INamedTypeSymbol { IsTupleType: true } tuple => "(" + string.Join(", ", tuple.TupleElements.Select(e => Type(e.Type))) + ")",
        _ => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
    };
    private static string PatternType(ITypeSymbol type) => type is INamedTypeSymbol { IsTupleType: true } tuple
        ? "global::System.ValueTuple<" + string.Join(", ", tuple.TupleElements.Select(e => Type(e.Type))) + ">" : Type(type);
    private void Line(string value) => code.AppendLine(value);
    private static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
    private static string Interface(INamedTypeSymbol type) => (string)type.GetAttributes().Single(a => a.AttributeClass?.Name == "DBusInterfaceAttribute").ConstructorArguments[0].Value!;
    private static bool Watch(IMethodSymbol method) => method.Name.StartsWith("Watch", StringComparison.Ordinal);
    private static bool Property(IMethodSymbol method) => method.Name is "GetAsync" or "GetAllAsync" or "SetAsync";
    private static ITypeSymbol? Result(IMethodSymbol method) => ((INamedTypeSymbol)method.ReturnType).TypeArguments.FirstOrDefault();
    private static ITypeSymbol? Signal(IMethodSymbol method) => ((INamedTypeSymbol)method.Parameters[0].Type).TypeArguments.FirstOrDefault();
    private static bool SingleArgument(IMethodSymbol method) => (Watch(method) ? method.Parameters[0].GetAttributes() : method.GetReturnTypeAttributes()).Any(a => a.AttributeClass?.Name == "ArgumentAttribute");
    private static IEnumerable<ITypeSymbol> Parts(ITypeSymbol type, bool single) => !single && type is INamedTypeSymbol { IsTupleType: true } tuple ? tuple.TupleElements.Select(e => e.Type) : [type];
    private static string Member(IMethodSymbol method) => method.Name[(Watch(method) ? 5 : 0)..^5];

    internal static string Generate(string directory, string protocolAssembly)
    {
        var paths = new[] { "DesktopBusContracts.cs", "DesktopBus.cs", "AccessibilityBus.cs" }.Select(p => Path.Combine(directory, p));
        var trees = paths.Select(p => CSharpSyntaxTree.ParseText(File.ReadAllText(p))).Append(CSharpSyntaxTree.ParseText("""
            global using System; global using System.Collections.Generic; global using System.Threading; global using System.Threading.Tasks;
            namespace Nazor.Platform.Linux;
            internal class VariantShapes {
                public byte[] Bytes = []; public string[] Strings = []; public int[] Integers = []; public uint[] Unsigned = [];
                public (int,int) TablePosition; public (int,int,byte[])[] Icons = []; public (string,(int,int,byte[])[],string,string) Tooltip;
                public (int,IDictionary<string,object>,object[]) Menu; public (string,(uint,string)[])[] Filters = [];
            }
            """));
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
            .Append(protocolAssembly).Distinct(StringComparer.OrdinalIgnoreCase).Select(p => MetadataReference.CreateFromFile(p));
        var compilation = CSharpCompilation.Create("DBus.Contracts", trees, references, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0) throw new InvalidDataException(string.Join(Environment.NewLine, errors.Select(d => d.ToString())));
        var ns = compilation.GlobalNamespace.GetNamespaceMembers().Single(n => n.Name == "Nazor").GetNamespaceMembers().Single(n => n.Name == "Platform").GetNamespaceMembers().Single(n => n.Name == "Linux");
        var interfaces = ns.GetTypeMembers().Where(t => t.GetAttributes().Any(a => a.AttributeClass?.Name == "DBusInterfaceAttribute")).ToArray();
        var generator = new DBusBindings();
        generator.Line("// <auto-generated/> Regenerate with nazorc dbus-bindings. Contracts: DesktopBusContracts.cs, DesktopBus.cs, AccessibilityBus.cs.");
        generator.Line("#nullable enable\nusing Tmds.DBus.Protocol;\nusing P = Tmds.DBus.Protocol;\nnamespace Nazor.Platform.Linux;\ninternal static partial class DesktopBindings {");
        generator.Line("internal static T Proxy<T>(DesktopConnection c, string service, ObjectPath path) where T : class, IDBusObject {");
        foreach (var type in interfaces) generator.Line($"if (typeof(T) == typeof({type.Name})) return (T)(object)new Proxy_{type.Name}(c, service, path);");
        generator.Line("throw new NotSupportedException(typeof(T).FullName); }");
        foreach (var type in interfaces) generator.Proxy(type);
        generator.Line("internal static async Task<List<IDisposable>> Subscribe(DesktopConnection c, IDBusObject value) { var subscriptions = new List<IDisposable>(); try {");
        foreach (var type in interfaces)
        {
            generator.Line($"if (value is {type.Name} v_{type.Name}) {{");
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(Watch))
            {
                var signal = Signal(method);
                var signature = signal is null ? "" : string.Concat(Parts(signal, SingleArgument(method)).Select(generator.Signature));
                var write = signal is null ? "" : generator.WriteParts(signal, SingleArgument(method), "payload");
                generator.Line($"subscriptions.Add(await v_{type.Name}.{method.Name}({(signal is null ? "()" : "payload")} => c.Signal(value.ObjectPath, {Literal(Interface(type))}, {Literal(Member(method))}, {Literal(signature)}, (ref P.MessageWriter w) => {{ {write} }})).ConfigureAwait(false));");
            }
            generator.Line("}");
        }
        generator.Line("return subscriptions; } catch { foreach (var s in subscriptions) s.Dispose(); throw; } }");
        generator.Line("internal static ValueTask Handle(IDBusObject value, P.MethodContext context) { var request = context.Request; var r = request.GetBodyReader(); var iface = request.InterfaceAsString; var member = request.MemberAsString; if (context.IsPropertiesInterfaceRequest) iface = r.ReadString();");
        foreach (var type in interfaces) generator.Handler(type);
        generator.Line("context.ReplyUnknownMethodError(); return default; }");
        generator.Line("internal static ReadOnlyMemory<byte>[] Introspection(IDBusObject value) { var xml = new List<ReadOnlyMemory<byte>>();");
        foreach (var type in interfaces)
        {
            var xml = new XElement("interface", new XAttribute("name", Interface(type)));
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(m => !Property(m)))
            {
                var node = new XElement(Watch(method) ? "signal" : "method", new XAttribute("name", Member(method)));
                foreach (var parameter in method.Parameters.Where(_ => !Watch(method))) node.Add(new XElement("arg", new XAttribute("type", generator.Signature(parameter.Type)), new XAttribute("direction", "in")));
                var result = Watch(method) ? Signal(method) : Result(method);
                if (result is not null) foreach (var part in Parts(result, SingleArgument(method))) node.Add(new XElement("arg", new XAttribute("type", generator.Signature(part)), new XAttribute("direction", "out")));
                xml.Add(node);
            }
            generator.Line($"if (value is {type.Name}) xml.Add(System.Text.Encoding.UTF8.GetBytes({Literal(xml.ToString(SaveOptions.DisableFormatting))}));");
        }
        generator.Line($"if ({string.Join(" || ", interfaces.Where(t => t.GetMembers().OfType<IMethodSymbol>().Any(Property)).Select(t => "value is " + t.Name))}) xml.Add(P.IntrospectionXml.DBusProperties);");
        generator.Line("return xml.ToArray(); }");
        foreach (var field in ns.GetTypeMembers("VariantShapes").Single().GetMembers().OfType<IFieldSymbol>()) generator.Codec(field.Type);
        for (var index = 0; index < generator.codecs.Count; index++)
        {
            var type = generator.codecs.Values.ElementAt(index).Type;
            if (type is IArrayTypeSymbol array) generator.Codec(array.ElementType);
            else if (Dictionary(type)) foreach (var argument in ((INamedTypeSymbol)type).TypeArguments) generator.Codec(argument);
            else if (Primitive(type) is null && type.SpecialType != SpecialType.System_Object && type.Name != "ObjectPath")
                foreach (var field in Fields(type)) generator.Codec(field.Type);
        }
        generator.Line("internal static void WriteVariant(ref P.MessageWriter w, object value) { switch(value) {");
        // Composite variant values used by desktop services, plus primitive values occurring only inside variants.
        foreach (var special in new[] { SpecialType.System_Byte, SpecialType.System_Boolean, SpecialType.System_Int16, SpecialType.System_UInt16, SpecialType.System_Int32, SpecialType.System_UInt32, SpecialType.System_Int64, SpecialType.System_UInt64, SpecialType.System_Double, SpecialType.System_String }) generator.Codec(compilation.GetSpecialType(special));
        foreach (var (_, item) in generator.codecs.ToArray().Where(p => p.Value.Type.SpecialType != SpecialType.System_Object))
            generator.Line($"case {PatternType(item.Type)} v{item.Id}: w.WriteSignature({Literal(generator.Signature(item.Type))}); Write{item.Id}(ref w, v{item.Id}); break;");
        generator.Line("default: throw new NotSupportedException(\"Unsupported desktop variant: \" + value.GetType().FullName); } }");
        for (var index = 0; index < generator.codecs.Count; index++) generator.EmitCodec(generator.codecs.Values.ElementAt(index));
        generator.Line("}");
        return generator.code.ToString();
    }

    private int Codec(ITypeSymbol type)
    {
        var key = Type(type);
        if (!codecs.TryGetValue(key, out var item)) codecs.Add(key, item = (type, codecs.Count));
        return item.Id;
    }
    private string Read(ITypeSymbol type) => $"Read{Codec(type)}(ref r)";
    private string Write(ITypeSymbol type, string value) => $"Write{Codec(type)}(ref w, {value});";
    private string WriteParts(ITypeSymbol type, bool single, string value) => !single && type is INamedTypeSymbol { IsTupleType: true } tuple
        ? string.Join(" ", tuple.TupleElements.Select((e, i) => Write(e.Type, value + ".Item" + (i + 1)))) : Write(type, value);
    private string ReadParts(ITypeSymbol type, bool single) => !single && type is INamedTypeSymbol { IsTupleType: true } tuple
        ? "(" + string.Join(", ", tuple.TupleElements.Select(e => Read(e.Type))) + ")" : Read(type);
    private static bool Dictionary(ITypeSymbol type) => type is INamedTypeSymbol named && named.Name is "IDictionary" or "Dictionary" && named.TypeArguments.Length == 2;
    private static (string Sig, string Method)? Primitive(ITypeSymbol type) => type.SpecialType switch {
        SpecialType.System_Byte => ("y", "Byte"), SpecialType.System_Boolean => ("b", "Bool"), SpecialType.System_Int16 => ("n", "Int16"), SpecialType.System_UInt16 => ("q", "UInt16"),
        SpecialType.System_Int32 => ("i", "Int32"), SpecialType.System_UInt32 => ("u", "UInt32"), SpecialType.System_Int64 => ("x", "Int64"), SpecialType.System_UInt64 => ("t", "UInt64"),
        SpecialType.System_Double => ("d", "Double"), SpecialType.System_String => ("s", "String"), _ => null };
    private string Signature(ITypeSymbol type)
    {
        if (Primitive(type) is { } primitive) return primitive.Sig;
        if (type.SpecialType == SpecialType.System_Object) return "v";
        if (type.Name == "ObjectPath") return "o";
        if (type is IArrayTypeSymbol array) return "a" + Signature(array.ElementType);
        if (Dictionary(type)) return "a{" + string.Concat(((INamedTypeSymbol)type).TypeArguments.Select(Signature)) + "}";
        return "(" + string.Concat(Fields(type).Select(f => Signature(f.Type))) + ")";
    }
    private static IEnumerable<IFieldSymbol> Fields(ITypeSymbol type) => type is INamedTypeSymbol { IsTupleType: true } tuple ? tuple.TupleElements : type.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic);
    private string WireType(ITypeSymbol type) => type is IArrayTypeSymbol || Dictionary(type) ? "Array" : type.SpecialType == SpecialType.System_Object ? "Variant" : type.Name == "ObjectPath" ? "ObjectPath" : Primitive(type)?.Method ?? "Struct";

    private void Proxy(INamedTypeSymbol type)
    {
        Line($"private sealed class Proxy_{type.Name}(DesktopConnection c, string service, ObjectPath path) : {type.Name} {{ public ObjectPath ObjectPath => path;");
        foreach (var method in type.GetMembers().OfType<IMethodSymbol>())
        {
            Line($"public {Type(method.ReturnType)} {method.Name}({string.Join(", ", method.Parameters.Select((p, i) => Type(p.Type) + " a" + i))}) {{");
            var result = Watch(method) ? Signal(method) : Result(method);
            if (Watch(method))
            {
                var reader = result is null ? "return 0;" : $"var r = message.GetBodyReader(); return {ReadParts(result, SingleArgument(method))};";
                Line($"return c.Watch(service, path, {Literal(Interface(type))}, {Literal(Member(method))}, static (message, _) => {{ {reader} }}, {(result is null ? "_ => a0()" : "a0")});");
            }
            else
            {
                var sig = string.Concat(method.Parameters.Select(p => Signature(p.Type)));
                Line($"var w = c.Raw.GetMessageWriter(); try {{ w.WriteMethodCallHeader(destination: service, path: path.ToString(), @interface: {Literal(Property(method) ? "org.freedesktop.DBus.Properties" : Interface(type))}, member: {Literal(Member(method))}, signature: {Literal((Property(method) ? "s" : "") + sig)});");
                if (Property(method)) Line($"w.WriteString({Literal(Interface(type))});");
                foreach (var (p, i) in method.Parameters.Select((p, i) => (p, i))) Line(Write(p.Type, "a" + i));
                Line(result is null ? "return c.Call(w.CreateMessage());" : $"return c.Call(w.CreateMessage(), static (message, _) => {{ var r = message.GetBodyReader(); return {ReadParts(result, SingleArgument(method))}; }});");
                Line("} finally { w.Dispose(); }");
            }
            Line("}");
        }
        Line("}");
    }

    private void Handler(INamedTypeSymbol type)
    {
        if (!type.GetMembers().OfType<IMethodSymbol>().Any(m => !Watch(m))) return;
        Line($"if (iface == {Literal(Interface(type))} && value is {type.Name} t_{type.Name}) {{ switch(member) {{");
        foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(m => !Watch(m)))
        {
            Line($"case {Literal(Member(method))}: {{");
            var signature = (Property(method) ? "s" : "") + string.Concat(method.Parameters.Select(p => Signature(p.Type)));
            Line($"if ((request.SignatureAsString ?? \"\") != {Literal(signature)}) {{ context.ReplyError(\"org.freedesktop.DBus.Error.InvalidArgs\", \"Invalid method signature.\"); return default; }}");
            foreach (var (p, i) in method.Parameters.Select((p, i) => (p, i))) Line($"var a{i} = {Read(p.Type)};");
            var call = $"t_{type.Name}.{method.Name}({string.Join(", ", method.Parameters.Select((_, i) => "a" + i))})";
            var result = Result(method);
            Line(result is null ? $"return DesktopConnection.Reply(context, {call});" : $"return DesktopConnection.Reply(context, {call}, {Literal(string.Concat(Parts(result, SingleArgument(method)).Select(Signature)))}, static (ref P.MessageWriter w, {Type(result)} result) => {{ {WriteParts(result, SingleArgument(method), "result")} }});");
            Line("}");
        }
        Line("} }");
    }

    private void EmitCodec((ITypeSymbol Type, int Id) item)
    {
        var (type, id) = item;
        string read, write;
        if (Primitive(type) is { } primitive) { read = $"return r.Read{primitive.Method}();"; write = $"w.Write{primitive.Method}(value);"; }
        else if (type.SpecialType == SpecialType.System_Object) { read = "return DesktopConnection.ReadVariant(r.ReadVariantValue());"; write = "WriteVariant(ref w, value);"; }
        else if (type.Name == "ObjectPath") { read = "return new ObjectPath(r.ReadObjectPathAsString());"; write = "w.WriteObjectPath(value.ToString());"; }
        else if (type is IArrayTypeSymbol array)
        {
            read = $"var values = new List<{Type(array.ElementType)}>(); var end = r.ReadArrayStart(P.DBusType.{WireType(array.ElementType)}); while (r.HasNext(end)) values.Add({Read(array.ElementType)}); return values.ToArray();";
            write = $"var start = w.WriteArrayStart(P.DBusType.{WireType(array.ElementType)}); foreach (var element in value) {{ {Write(array.ElementType, "element")} }} w.WriteArrayEnd(start);";
        }
        else if (Dictionary(type))
        {
            var args = ((INamedTypeSymbol)type).TypeArguments;
            read = $"var values = new Dictionary<{Type(args[0])}, {Type(args[1])}>(); var end = r.ReadArrayStart(P.DBusType.DictEntry); while (r.HasNext(end)) {{ r.AlignStruct(); var key = {Read(args[0])}; values.Add(key, {Read(args[1])}); }} return values;";
            write = $"var start = w.WriteArrayStart(P.DBusType.DictEntry); foreach (var element in value) {{ w.WriteStructureStart(); {Write(args[0], "element.Key")} {Write(args[1], "element.Value")} }} w.WriteArrayEnd(start);";
        }
        else
        {
            var fields = Fields(type).ToArray();
            read = "r.AlignStruct(); return " + (type is INamedTypeSymbol { IsTupleType: true } ? "(" + string.Join(", ", fields.Select(f => Read(f.Type))) + ")" : "new " + Type(type) + " { " + string.Join(", ", fields.Select(f => f.Name + " = " + Read(f.Type))) + " }") + ";";
            write = "w.WriteStructureStart(); " + string.Join(" ", fields.Select((f, i) => Write(f.Type, "value." + (type is INamedTypeSymbol { IsTupleType: true } ? "Item" + (i + 1) : f.Name))));
        }
        Line($"private static {Type(type)} Read{id}(ref P.Reader r) {{ {read} }}");
        Line($"private static void Write{id}(ref P.MessageWriter w, {Type(type)} value) {{ {write} }}");
    }
}
