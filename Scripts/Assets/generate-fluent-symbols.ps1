[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repositoryRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$themeRoot = Join-Path $repositoryRoot 'Sources/Themes/Nazor.Themes.Fluent'
$catalogRoot = Join-Path $themeRoot 'Catalog'
$source = Get-Content -LiteralPath (Join-Path $catalogRoot 'Source.json') -Raw | ConvertFrom-Json -AsHashtable
foreach ($entry in $source.sha256.GetEnumerator()) {
    $hash = (Get-FileHash -LiteralPath (Join-Path $catalogRoot $entry.Key) -Algorithm SHA256).Hash
    if ($hash -ne $entry.Value) { throw "Fluent source hash mismatch: $($entry.Key). Update fonts, maps and Source.json together." }
}

$outputs = [ordered]@{}
$reference = [Text.StringBuilder]::new()
[void]$reference.Append("### ``FluentSymbol```n`nNamespace ``Nazor.Themes.Fluent``. [Source](../../Sources/Themes/Nazor.Themes.Fluent/FluentSymbol.cs)`n`n")
[void]$reference.Append("Members are generated from Fluent UI System Icons $($source.version), commit ``$($source.commit)``. Names contain the design size and variant, followed by a locale suffix where supplied upstream. Sizes identify the source artwork; NSS controls the displayed size. Regular and Filled have independent mappings. The default struct value is empty and cannot be used as an active symbol.`n`n")
[void]$reference.Append('| Declaration | Contract |' + "`n| --- | --- |`n")
[void]$reference.Append('| `public readonly struct FluentSymbol : IFontSymbol` | A typed icon and its matching private font family. |' + "`n")
[void]$reference.Append('| `public FluentSymbol()` | Creates the empty default value. |' + "`n")
[void]$reference.Append('| `public string FontFamily { get; }` | Internal family name; empty for the default value. |' + "`n")
[void]$reference.Append('| `public string Glyph { get; }` | Unicode glyph text, including surrogate pairs; empty for the default value. |' + "`n")

$total = 0
$identifiers = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($variant in @('Regular', 'Filled')) {
    $map = Get-Content -LiteralPath (Join-Path $catalogRoot "FluentSystemIcons-$variant.json") -Raw | ConvertFrom-Json -AsHashtable
    $members = [Collections.Generic.SortedDictionary[string, string]]::new([StringComparer]::Ordinal)
    foreach ($entry in $map.GetEnumerator()) {
        if ($entry.Key -cnotmatch ('^ic_fluent_[a-z0-9_]+_[0-9]+_' + $variant.ToLowerInvariant() + '(?:_[a-z0-9_]+)?$')) {
            throw "Unexpected Fluent symbol name: $($entry.Key)"
        }
        $identifier = ($entry.Key.Substring(10) -split '_' | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join ''
        if ($identifier -match '^[0-9]') { $identifier = 'Icon' + $identifier }
        if (!$identifiers.Add($identifier)) { throw "Duplicate Fluent symbol identifier: $identifier" }
        $scalar = [int]$entry.Value
        if (![Text.Rune]::IsValid($scalar)) { throw "Invalid Unicode scalar for $($entry.Key): $scalar" }
        $literal = if ($scalar -le 0xffff) { '\u{0:X4}' -f $scalar } else { '\U{0:X8}' -f $scalar }
        $members.Add($identifier, $literal)
    }
    $code = [Text.StringBuilder]::new()
    [void]$code.Append("// <auto-generated/>`nnamespace Nazor.Themes.Fluent;`n`npublic readonly partial struct FluentSymbol`n{`n")
    foreach ($member in $members.GetEnumerator()) {
        [void]$code.Append("    /// <summary>Gets the $($member.Key) font symbol.</summary>`n")
        [void]$code.Append('    public static FluentSymbol ' + $member.Key + ' => new("FluentSystemIcons-' + $variant + '", "' + $member.Value + '");' + "`n`n")
        [void]$reference.Append('| `public static FluentSymbol ' + $member.Key + ' { get; }` | ' + $variant + ' icon, glyph `' + $member.Value + '`. |' + "`n")
    }
    [void]$code.Append("}`n")
    $outputs[(Join-Path $themeRoot "FluentSymbol.$variant.g.cs")] = $code.ToString()
    $total += $members.Count
}

$referencePath = Join-Path $repositoryRoot 'Docs/ApiReferences/Nazor.Themes.Fluent.md'
$markdown = [IO.File]::ReadAllText($referencePath).Replace("`r`n", "`n")
$pattern = '(?s)(<!-- fluent-symbol-catalog:start -->\n).*?(<!-- fluent-symbol-catalog:end -->)'
if ([regex]::Matches($markdown, $pattern).Count -ne 1) { throw 'Expected exactly one Fluent symbol reference marker pair.' }
$replacement = $reference.ToString() + "`n"
$outputs[$referencePath] = [regex]::Replace($markdown, $pattern, [Text.RegularExpressions.MatchEvaluator]{ param($match) $match.Groups[1].Value + $replacement + $match.Groups[2].Value })

foreach ($entry in $outputs.GetEnumerator()) {
    if ($Check) {
        if (!(Test-Path -LiteralPath $entry.Key) -or [IO.File]::ReadAllText($entry.Key).Replace("`r`n", "`n") -cne $entry.Value) {
            throw "Generated Fluent catalog is stale: $($entry.Key)"
        }
    } else {
        [IO.File]::WriteAllText($entry.Key, $entry.Value, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output "Fluent UI System Icons $($source.version): $total symbols; font/map hashes and generated outputs verified."
